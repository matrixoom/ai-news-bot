def get_official_quarterly_real_growth(period_end: str) -> float | None:
    """获取某季度官方公布的实际 GDP 当季同比增速。

    Args:
        period_end: 季度结束日期，如 "2020-06-30"。

    Returns:
        增速值（%），若未收录则返回 None。
    """
    return _OFFICIAL_QUARTERLY_REAL_GROWTH.get(period_end)


